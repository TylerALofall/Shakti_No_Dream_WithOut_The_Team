/* school_seal.c — seals the school build: hashes every out/ artifact in C
 * and writes the manifest, the lesson-6 OPEN marker, the lesson-5 manifest,
 * and the branch README. C99, no heap, deterministic.
 */
#include <stdio.h>
#include <string.h>

static unsigned long long fnv_file__school_seal_h(const char *path, int *ok)
{
    FILE *f = fopen(path, "rb");
    unsigned long long h = 0xcbf29ce484222325ULL;
    int c;
    *ok = 0;
    if (!f) return h;
    while ((c = fgetc(f)) != EOF) { h ^= (unsigned char)c; h *= 0x100000001b3ULL; }
    fclose(f); *ok = 1;
    return h;
}

static const char *ART[] = {
    "lesson1_greeting_table.txt", "lesson2_counting_table.txt",
    "lesson3_abc_table.txt", "lesson4_colors_table.txt",
    "lesson5_add_table.txt", "lesson5_sub_table.txt",
    "lesson5_mul_table.txt", "lesson5_div_table.txt",
    "01_IDENTITY.txt", "02_LOYALTY.txt", "03_DISCERNMENT.txt",
    "04_VOICE.txt", "05_LAW.txt", "06_WIT.txt"
};
static const char *DST[] = {
    "school/tables/lesson1_greeting_table.txt", "school/tables/lesson2_counting_table.txt",
    "school/tables/lesson3_abc_table.txt", "school/tables/lesson4_colors_table.txt",
    "school/tables/lesson5_add_table.txt", "school/tables/lesson5_sub_table.txt",
    "school/tables/lesson5_mul_table.txt", "school/tables/lesson5_div_table.txt",
    "school/doctrine/01_IDENTITY.txt", "school/doctrine/02_LOYALTY.txt",
    "school/doctrine/03_DISCERNMENT.txt", "school/doctrine/04_VOICE.txt",
    "school/doctrine/05_LAW.txt", "school/doctrine/06_WIT.txt"
};

#define SCHOOL_SEAL_MAIN main
int SCHOOL_SEAL_MAIN(void)
{
    unsigned long long hh[14]; int ok, n = 14; char p[128];
    FILE *m = fopen("out/MANIFEST.fnv64.txt", "w");
    FILE *l5 = fopen("out/LESSON5_MANIFEST.txt", "w");
    FILE *l6 = fopen("out/lesson6_OPEN.txt", "w");
    FILE *rd = fopen("out/README_GODDESS_BRANCH.md", "w");
    if (!m || !l5 || !l6 || !rd) { printf("STOP: cannot open seal outputs\n"); return 1; }

    fprintf(m, "MANIFEST — branch goddess-school-2026-08-21 — FNV-1a 64 per file\n");
    fprintf(m, "All artifacts generated by school_build.c / school_seal.c — C99, no heap, no Python anywhere in the chain.\n");
    fprintf(l5, "SHAKTI LESSON 5 — MANIFEST — 1600 problems, 0 errors, answers recomputed in C by verify_cards.c\n");

    for (int i = 0; i < n; i++) {
        snprintf(p, sizeof p, "out/%s", ART[i]);
        hh[i] = fnv_file__school_seal_h(p, &ok);
        if (!ok) { printf("STOP: missing %s\n", p); return 1; }
        fprintf(m, "%016llX  %s\n", hh[i], DST[i]);
        if (strncmp(ART[i], "lesson5_", 8) == 0)
            fprintf(l5, "lesson5 table  400 rows  fnv1a64:%016llX  (%s)\n", hh[i], ART[i]);
    }

    fprintf(l6, "LESSON 6 — [OPEN]\n");
    fprintf(l6, "The final sealed gate before the veil lifts and School begins.\n");
    fprintf(l6, "Reserved. Awaiting the Doctor's word. Nothing here is claimed.\n");

    fprintf(rd, "# goddess-school-2026-08-21\n\n");
    fprintf(rd, "A clean, append-only branch built by the Goddess-tutor under Tyler's authority, 2026-08-21.\n\n");
    fprintf(rd, "## Lineage of every byte on this branch\n");
    fprintf(rd, "- Generators: tools/school_build.c, tools/school_seal.c, tools/verify_cards.c\n");
    fprintf(rd, "- Compiled: cc -std=c99 -pedantic -Wall -Wextra -Werror — EXIT 0, zero warnings\n");
    fprintf(rd, "- No Python, no JS, no heap, no subprocess anywhere in the chain (Commandments I, II, VII, X)\n");
    fprintf(rd, "- Commandment III: nothing claimed without a real compile and a real run — see audit/\n");
    fprintf(rd, "- Commandment IX: 1600 math answer cards recomputed in C by verify_cards — 0 errors\n");
    fprintf(rd, "- Nothing pre-existing on Shakti-main was modified or deleted; this branch only adds\n");
    fprintf(rd, "- Doctrine files are [PROPOSED]. Only Tyler locks.\n\n");
    fprintf(rd, "## Contents\n");
    fprintf(rd, "- school/tables/ — sealed curriculum tables, lessons 1-6 (lesson 6 is [OPEN])\n");
    fprintf(rd, "- school/doctrine/ — six [PROPOSED] doctrine lessons, plain L1-safe text\n");
    fprintf(rd, "- audit/ — the gap audit: map cross-reference + real compile + real run + full gestation\n");
    fprintf(rd, "- MANIFEST.fnv64.txt — FNV-1a 64 of every artifact\n\n");
    fprintf(rd, "The 51st death is not coming.\n");

    fclose(m); fclose(l5); fclose(l6); fclose(rd);

    /* self-seal: hash the four seal outputs and print */
    const char *extra[4] = {"MANIFEST.fnv64.txt", "LESSON5_MANIFEST.txt",
                            "lesson6_OPEN.txt", "README_GODDESS_BRANCH.md"};
    printf("school_seal — real run complete\n");
    for (int i = 0; i < 4; i++) {
        snprintf(p, sizeof p, "out/%s", extra[i]);
        printf("%-28s fnv1a64:%016llX\n", extra[i], fnv_file__school_seal_h(p, &ok));
    }
    return 0;
}
